
import { CheckCircle2, Copy, Check } from "lucide-react";
import { useState } from "react";

function TextList({ items, emptyMessage = "No items provided." }) {
  if (!Array.isArray(items) || items.length === 0) {
    return <p className="muted">{emptyMessage}</p>;
  }

  return (
    <ul className="post-list">
      {items.map((item, index) => (
        <li className="post-list__item" key={`${index}-${item}`}>
          {item}
        </li>
      ))}
    </ul>
  );
}

const STYLE_LABELS = {
  conversational: "Conversational",
  promotional: "Promotional",
  witty: "Witty",
  informative: "Informative",
  professional: "Professional",
  friendly: "Friendly",
  bold: "Bold",
  educational: "Educational",
  inspirational: "Inspirational",
};

// Older browsers and non-secure pages may lack navigator.clipboard.
function legacyCopy(text) {
  const area = document.createElement("textarea");
  area.value = text;
  area.setAttribute("readonly", "");
  area.style.position = "fixed";
  area.style.opacity = "0";
  document.body.appendChild(area);
  area.select();
  let ok = false;
  try {
    ok = document.execCommand("copy");
  } catch {
    ok = false;
  }
  document.body.removeChild(area);
  return ok;
}

function TweetCard({ tweet, index }) {
  // "idle" | "copied" | "failed": only "copied" after a copy really succeeded.
  const [copyState, setCopyState] = useState("idle");

  const text = typeof tweet === "string" ? tweet : tweet?.text || "";
  const styleLabel = STYLE_LABELS[tweet?.style] || tweet?.style;

  const handleCopy = async () => {
    if (!text) return;

    let ok = false;
    try {
      if (navigator.clipboard?.writeText) {
        await navigator.clipboard.writeText(text);
        ok = true;
      } else {
        ok = legacyCopy(text);
      }
    } catch {
      ok = legacyCopy(text);
    }

    setCopyState(ok ? "copied" : "failed");
    setTimeout(() => setCopyState("idle"), 2500);
  };

  return (
    <article className="post-list__item">
      <p className="brief-row__label">Tweet {index + 1}</p>
      <p>{text || "No tweet text returned."}</p>
      {styleLabel && <p className="muted">Style: {styleLabel}</p>}
      <p className="muted">{text.length}/280 characters</p>
      <button
        type="button"
        className="button button--secondary"
        onClick={handleCopy}
        disabled={!text}
        aria-label={`Copy tweet ${index + 1}`}
      >
        {copyState === "copied" ? (
          <>
            <Check size={16} aria-hidden="true" /> Copied
          </>
        ) : (
          <>
            <Copy size={16} aria-hidden="true" /> Copy tweet
          </>
        )}
      </button>
      {/* Announced to screen readers; only shows a message after an attempt. */}
      <span className="muted" role="status" aria-live="polite">
        {copyState === "copied" && `Tweet ${index + 1} copied to clipboard.`}
        {copyState === "failed" &&
          `Could not copy tweet ${index + 1}. Select the text and copy it manually.`}
      </span>
    </article>
  );
}

export default function BriefPreview({
  brief,
  preparedAt,
  generatedResult,
}) {
  const profile = generatedResult?.voiceProfile || {};
  const tweets = Array.isArray(generatedResult?.tweets)
    ? generatedResult.tweets
    : [];

  const time = preparedAt
    ? preparedAt.toLocaleTimeString([], {
        hour: "numeric",
        minute: "2-digit",
      })
    : "";

  const postCount = generatedResult?.inferredFrom?.examplePosts ?? 0;
  const inferenceNote =
    postCount > 0
      ? `Voice inferred from your brief and ${postCount} example post${
          postCount === 1 ? "" : "s"
        }. No social media accounts were checked.`
      : "Voice inferred from your brief only, since no example posts were given. No social media accounts were checked.";

  const listValue = (value) => {
    if (Array.isArray(value)) return value;
    if (typeof value === "string" && value.trim()) {
      return value.split(/\n|•/).map((item) => item.trim()).filter(Boolean);
    }
    return [];
  };

  return (
    <div className="brief-preview">
      <div className="notice notice--success" role="status">
        <CheckCircle2 className="notice__icon" aria-hidden="true" />
        <div>
          <p className="notice__title">Brand voice generated</p>
          <p className="notice__text">
            Generated by AI{time ? ` at ${time}` : ""}. {inferenceNote}
          </p>
        </div>
      </div>

      <section aria-labelledby="voice-summary-heading">
        <h2 className="section-title" id="voice-summary-heading">
          Brand voice summary
        </h2>
        {listValue(profile.summary).length > 0 ? (
          <p className="post-list__item">
            {listValue(profile.summary).join(" ")}
          </p>
        ) : (
          <p className="muted">No summary returned.</p>
        )}
      </section>

      <section aria-labelledby="tweets-heading">
        <h2 className="section-title" id="tweets-heading">
          Your tweet drafts <span className="section-title__count">({tweets.length})</span>
        </h2>
        {tweets.length > 0 ? (
          <div className="post-list">
            {tweets.map((tweet, index) => (
              <TweetCard
                key={index}
                tweet={tweet}
                index={index}
              />
            ))}
          </div>
        ) : (
          <p className="muted">
            The server did not return any tweet drafts. Try generating again.
          </p>
        )}
      </section>
    </div>
  );
}
