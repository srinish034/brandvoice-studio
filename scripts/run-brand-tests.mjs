// Runs two contrasting test briefs through the REAL /api/generate route
// (real Gemini call, your GEMINI_API_KEY from .env) and saves the results.
//
//   npm run test:brands
//
// Outputs: evidence/nike-style-sports.json, evidence/premium-skincare.json,
//          evidence/brand-comparison.md
// The briefs are test examples with fictional product details. They are not
// claims about any company's official brand guidelines.
import "dotenv/config";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createApp } from "../server/app.js";
import { TWEET_STYLES } from "../server/outputSchema.js";

const outDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "evidence");
fs.mkdirSync(outDir, { recursive: true });

if (!process.env.GEMINI_API_KEY) {
  console.error("GEMINI_API_KEY is not set. Copy .env.example to .env and add your key.");
  process.exit(1);
}

const briefs = {
  "nike-style-sports": {
    brandName: "Nike",
    industry: "Other",
    objective: "Product launch",
    products:
      "Test scenario with fictional details: launch of a new running shoe called the 'Stride Pro' for competitive and everyday runners. Lightweight design, responsive cushioning, built for race day and daily training.",
    audience: "Competitive and aspiring runners aged 18-40",
    tone: "Bold",
    socialPosts:
      "Just do it. Every mile counts.\nYour only limit is you.\nNo finish line. Only the next one.\nChampions train when nobody is watching.",
  },
  "premium-skincare": {
    brandName: "Lumière Atelier",
    industry: "Health",
    objective: "Brand awareness",
    products:
      "Test scenario with fictional details: a premium skincare brand introducing a gentle daily serum and a night cream. Focus on calm routines, thoughtful ingredients and long-term skin care rather than quick fixes.",
    audience: "Adults who value minimalist, considered self-care routines",
    tone: "Professional",
    socialPosts:
      "Skin care is a quiet ritual, not a race.\nGentle by design. Considered in every detail.\nSlow mornings. Calm skin.",
  },
};

const app = createApp({ env: { ...process.env, NODE_ENV: "test", RATE_LIMIT_MAX: "100" } });
const server = await new Promise((r) => {
  const s = app.listen(0, () => r(s));
});
const url = `http://127.0.0.1:${server.address().port}/api/generate`;

const tokens = (text) =>
  new Set(text.toLowerCase().replace(/[^\p{L}\p{N}\s']/gu, " ").split(/\s+/).filter((w) => w.length > 3));

const results = {};
let failures = 0;
const log = [];
const record = (ok, msg) => {
  if (!ok) failures += 1;
  const line = `${ok ? "PASS" : "FAIL"}  ${msg}`;
  console.log(line);
  log.push(line);
};

for (const [name, brief] of Object.entries(briefs)) {
  console.log(`\n== ${name} ==`);
  const res = await fetch(url, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify(brief),
  });
  const data = await res.json();
  record(res.status === 200 && data.status === "success", `${name}: generation succeeded (HTTP ${res.status})`);
  if (res.status !== 200) continue;

  fs.writeFileSync(
    path.join(outDir, `${name}.json`),
    JSON.stringify({ request: brief, response: data }, null, 2)
  );
  results[name] = data;

  const p = data.voiceProfile;
  record(data.tweets.length === 10, `${name}: exactly 10 tweets`);
  record(p.summary.length >= 3 && p.summary.length <= 4, `${name}: summary has ${p.summary.length} bullets`);
  const counts = Object.fromEntries(TWEET_STYLES.map((s) => [s, data.tweets.filter((t) => t.style === s).length]));
  record(Object.values(counts).filter((n) => n > 0).length >= 3, `${name}: style mix ${JSON.stringify(counts)}`);
  record(data.tweets.every((t) => t.text.length <= 280), `${name}: all tweets <= 280 chars`);
}

server.close();

const names = Object.keys(results);
if (names.length === 2) {
  const [a, b] = names;
  const ta = tokens(results[a].tweets.map((t) => t.text).join(" "));
  const tb = tokens(results[b].tweets.map((t) => t.text).join(" "));
  const shared = [...ta].filter((w) => tb.has(w));
  const overlap = shared.length / Math.min(ta.size, tb.size);
  const avg = (r) => Math.round(r.tweets.reduce((n, t) => n + t.text.length, 0) / r.tweets.length);

  const md = [
    "# Brand comparison (generated by scripts/run-brand-tests.mjs)",
    "",
    `Run on: ${new Date().toISOString()}  |  Model: ${process.env.GEMINI_MODEL || "gemini-3.5-flash-lite"}`,
    "",
    "Automated checks:",
    "",
    "```",
    ...log,
    "```",
    "",
    `Vocabulary overlap between the two tweet sets (words over 3 letters): ${(overlap * 100).toFixed(0)}% - shared words: ${shared.slice(0, 25).join(", ") || "none"}`,
    `Average tweet length: ${a} ${avg(results[a])} chars, ${b} ${avg(results[b])} chars`,
    "",
    ...names.flatMap((n) => [
      `## ${n}`,
      "",
      "**Summary**",
      ...results[n].voiceProfile.summary.map((s) => `- ${s}`),
      "",
      "**Tweets**",
      ...results[n].tweets.map((t, i) => `${i + 1}. [${t.style}] ${t.text}`),
      "",
    ]),
    "## Manual review still required",
    "",
    "The script cannot judge these; read both files and confirm before you submit:",
    "- The two sets differ clearly in tone, vocabulary and messaging.",
    "- Tweets are not repetitive and invent no offers, prices, statistics or product claims.",
    "",
  ].join("\n");
  fs.writeFileSync(path.join(outDir, "brand-comparison.md"), md);
  console.log(`\nVocabulary overlap: ${(overlap * 100).toFixed(0)}%. Saved evidence/ files.`);
}

console.log(failures === 0 ? "\nAll automated checks passed." : `\n${failures} automated check(s) FAILED.`);
process.exit(failures === 0 ? 0 : 1);
